#!/usr/bin/env python3
"""Build the screen's CJK font from Source Han Sans (思源黑体) for the SD card (collector-0.4.95-font).

  python3 scripts/generate-cjk-font.py --fetch .cache/ui-font/source   # download + verify the pinned release
  python3 scripts/generate-cjk-font.py --font path/to/SourceHanSansCN-Medium.otf
  python3 scripts/generate-cjk-font.py --check                         # parts on disk = manifest = firmware

The source is Adobe's Source Han Sans 2.005R, region subset CN (identical design to Noto Sans CJK SC), SIL OFL 1.1.
Both the release zip and the OTF inside it are pinned by SHA-256 below; anything else is refused.
lv_font_conv 1.5.3 (.tools/ui-assets, as for collector_mono_15) rasterizes each variant to LVGL's binary font;
ui_font_tools.pack() turns that into the HCJK container the robot keeps in PSRAM. Each container is cut into
<= 256 KiB parts (the SD installer's per-file bound) under assets/ui-font/sdcard/soul/font/ (git-ignored: about
1.1 MB); the committed manifest.json and the firmware's ui_font_catalog.generated.h pin every part's size and hash.
"""
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import ui_font_tools as tools  # noqa: E402

RELEASE_URL = 'https://github.com/adobe-fonts/source-han-sans/releases/download/2.005R/19_SourceHanSansCN.zip'
RELEASE_SHA256 = '3a769d1b082ebd813cdb4c06ea57d29b340bce548edcc8e61976b78ca28e6236'   # GitHub release asset digest
OTF_MEMBER = 'SubsetOTF/CN/SourceHanSansCN-Medium.otf'
OTF_SHA256 = 'a94e558a2fe972bee4f46bce0843abff37063fd68c33f1e7d9058f6f09432b01'
LICENSE_MEMBER = 'LICENSE.txt'
LICENSE_SHA256 = 'fcac737e761ec63dbfbdce11030a1780161920d80315edba9c8beff1c2bac5a2'
CONVERTER_VERSION = '1.5.3'
PART_BYTES = 262144
# (id, px, bpp). Readability check on the 320x240 panel (2026-11-14): at 16 px 2 bpp makes strokes blotchy, so
# 4 bpp; at 24 px 2 bpp and 4 bpp look the same, so 2 bpp (half the bytes). Medium reads better than Regular on
# the dark background at arm's length.
VARIANTS = (('cjk16', 16, 4), ('cjk24', 24, 2))

ASSETS = ROOT / 'assets/ui-font'
PARTS = ASSETS / 'sdcard/soul/font'
MANIFEST = ASSETS / 'manifest.json'
LICENSE = ASSETS / 'LICENSE-OFL.txt'
HEADER = ROOT / 'upstream/StackChan/firmware/main/collector/ui_font_catalog.generated.h'
EXTRA = ROOT / 'config/ui-font-extra.txt'


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def fetch(directory):
    """Download the pinned release zip into an empty directory; extract only the OTF and the license."""
    directory.mkdir(parents=True, exist_ok=True)
    if any(directory.iterdir()):
        sys.exit(f'{directory} must be empty (downloads are untrusted; keep them apart)')
    archive = directory / '19_SourceHanSansCN.zip'
    subprocess.run(['/usr/bin/curl', '-q', '--proto', '=https', '--fail', '--location', '--silent', '--show-error',
                    '--output', str(archive), RELEASE_URL], check=True)
    if sha256(archive.read_bytes()) != RELEASE_SHA256:
        sys.exit('release zip SHA-256 mismatch; nothing extracted')
    with zipfile.ZipFile(archive) as z:
        otf = z.read(OTF_MEMBER)
        text = z.read(LICENSE_MEMBER)
    if sha256(otf) != OTF_SHA256 or sha256(text) != LICENSE_SHA256:
        sys.exit('OTF / license SHA-256 mismatch')
    (directory / Path(OTF_MEMBER).name).write_bytes(otf)
    (directory / 'LICENSE.txt').write_bytes(text)
    return directory / Path(OTF_MEMBER).name


def converter(path):
    package = Path(path).resolve().parent.parent / 'lv_font_conv/package.json'
    version = json.loads(package.read_text()).get('version') if package.exists() else None
    if version != CONVERTER_VERSION:
        sys.exit(f'lv_font_conv {CONVERTER_VERSION} required (found {version}); see docs/build.md')
    return str(path)


def build_variant(conv, otf, chars, px, bpp):
    with tempfile.TemporaryDirectory(prefix='ui-font-') as tmp:
        out = Path(tmp) / 'font.bin'
        subprocess.run([conv, '--font', str(otf), '--symbols', ''.join(chars), '--size', str(px), '--bpp', str(bpp),
                        '--format', 'bin', '--no-compress', '--no-kerning', '-o', str(out)],
                       check=True, stdout=subprocess.DEVNULL)
        font = tools.parse_lvgl_bin(out.read_bytes())
    blob = tools.pack(font)
    font = tools.unpack(blob)
    missing = [c for c in chars if ord(c) not in font['codepoints']]
    if missing:
        sys.exit(f'{px} px font lacks {"".join(missing)!r}')
    return blob


def header_text(manifest):
    hexbytes = lambda h: ','.join(f'0x{h[i:i + 2]}' for i in range(0, 64, 2))
    lines = ['// Generated by scripts/generate-cjk-font.py; do not edit.',
             f'// {manifest["source"]["name"]}, SIL OFL 1.1 (assets/ui-font/LICENSE-OFL.txt).',
             '#pragma once', '#include <cstddef>', '#include <cstdint>', 'namespace collector::ui_font {',
             'struct Part { const char* path; uint32_t bytes; uint8_t sha256[32]; };',
             'struct Variant { const char* id; uint8_t px, bpp; uint32_t bytes; uint8_t part_count; const Part* parts; };']
    for v in manifest['variants']:
        lines.append(f'inline constexpr Part k{v["id"].capitalize()}Parts[] = {{')
        for p in v['parts']:
            lines.append(f'    {{"/{p["path"]}",{p["bytes"]},{{{hexbytes(p["sha256"])}}}}},')
        lines.append('};')
    lic = manifest['license']
    lines.append('// The OFL text travels with the font: installed next to the parts (X-Font-Part "license").')
    lines.append(f'inline constexpr Part kLicense = {{"/{lic["path"]}",{lic["bytes"]},{{{hexbytes(lic["sha256"])}}}}};')
    lines.append(f'inline constexpr size_t kVariantCount = {len(manifest["variants"])};')
    lines.append('inline constexpr Variant kVariants[kVariantCount] = {')
    for v in manifest['variants']:
        lines.append(f'    {{"{v["id"]}",{v["px"]},{v["bpp"]},{v["bytes"]},{len(v["parts"])},k{v["id"].capitalize()}Parts}},')
    lines += ['};', f'inline constexpr size_t kPartBytes = {PART_BYTES};', '}', '']
    return '\n'.join(lines)


def generate(otf, conv, preview):
    if sha256(otf.read_bytes()) != OTF_SHA256:
        sys.exit(f'{otf}: not the pinned {OTF_MEMBER} (SHA-256 mismatch)')
    release_license = otf.parent / 'LICENSE.txt'
    if release_license.exists() and sha256(release_license.read_bytes()) == LICENSE_SHA256:
        ASSETS.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(release_license, LICENSE)
    if not LICENSE.exists() or sha256(LICENSE.read_bytes()) != LICENSE_SHA256:
        sys.exit('the release LICENSE.txt must sit next to the OTF (--fetch puts it there)')
    chars = tools.charset(tools.read_extra(EXTRA))
    PARTS.mkdir(parents=True, exist_ok=True)
    for old in PARTS.glob('*.bin'):
        old.unlink()
    manifest = {'format': 'HCJK v1 (scripts/ui_font_tools.py)',
                'source': {'name': 'Source Han Sans 2.005R (思源黑体), SourceHanSansCN-Medium.otf', 'url': RELEASE_URL,
                           'release_sha256': RELEASE_SHA256, 'otf_sha256': OTF_SHA256, 'license': 'SIL OFL 1.1'},
                'converter': f'lv_font_conv {CONVERTER_VERSION} --no-compress --no-kerning',
                'charset': {'count': len(chars), 'sha256': sha256(''.join(chars).encode()),
                            'sets': 'ASCII 0x20-0x7E, GB2312 rows 1 and 3, GB2312 level 1 (3755), config/ui-font-extra.txt'},
                'part_bytes': PART_BYTES,
                'license': {'path': 'sdcard/soul/font/LICENSE-OFL.txt', 'source': 'assets/ui-font/LICENSE-OFL.txt',
                            'bytes': LICENSE.stat().st_size, 'sha256': LICENSE_SHA256},
                'variants': []}
    blobs = {}
    for vid, px, bpp in VARIANTS:
        blob = build_variant(conv, otf, chars, px, bpp)
        blobs[vid] = blob
        parts = []
        for n, at in enumerate(range(0, len(blob), PART_BYTES)):
            data = blob[at:at + PART_BYTES]
            name = f'{vid}.{n}.bin'
            (PARTS / name).write_bytes(data)
            parts.append({'path': f'sdcard/soul/font/{name}', 'bytes': len(data), 'sha256': sha256(data)})
        manifest['variants'].append({'id': vid, 'px': px, 'bpp': bpp, 'bytes': len(blob), 'sha256': sha256(blob),
                                     'glyphs': len(tools.unpack(blob)['glyphs']), 'parts': parts})
        print(f'{vid}: {px} px {bpp} bpp, {len(blob)} bytes in {len(parts)} parts')
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    HEADER.write_text(header_text(manifest), encoding='utf-8')
    if preview:
        sample = '模式 脱口秀 对话 设置 事件驱动 字幕 围观 陪伴 IDLE'
        rows = []
        for vid in blobs:
            rows += tools.render(tools.unpack(blobs[vid]), sample, 320) + [[(80, 80, 80)] * 320]
        preview.parent.mkdir(parents=True, exist_ok=True)
        tools.write_png(preview, rows, scale=2)
        print(f'preview: {preview}')


def check():
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    if HEADER.read_text(encoding='utf-8') != header_text(manifest):
        sys.exit('ui_font_catalog.generated.h is out of date with manifest.json')
    if sha256(LICENSE.read_bytes()) != LICENSE_SHA256:
        sys.exit('assets/ui-font/LICENSE-OFL.txt differs from the release license')
    chars = tools.charset(tools.read_extra(EXTRA))
    if manifest['charset']['sha256'] != sha256(''.join(chars).encode()):
        sys.exit('charset changed (config/ui-font-extra.txt?): run scripts/generate-cjk-font.py')
    present = 0
    for v in manifest['variants']:
        files = [PARTS / Path(p['path']).name for p in v['parts']]
        if not all(f.exists() for f in files):
            continue
        blob = b''.join(f.read_bytes() for f in files)
        if sha256(blob) != v['sha256'] or any(sha256(f.read_bytes()) != p['sha256'] for f, p in zip(files, v['parts'])):
            sys.exit(f'{v["id"]}: parts on disk differ from manifest.json')
        tools.unpack(blob)
        present += 1
    print(f'catalog OK; {present}/{len(manifest["variants"])} variants present locally')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--font', type=Path, help='SourceHanSansCN-Medium.otf (pinned SHA-256)')
    parser.add_argument('--fetch', type=Path, metavar='EMPTY_DIR', help='download and verify the release first')
    parser.add_argument('--converter', default=str(ROOT / '.tools/ui-assets/node_modules/.bin/lv_font_conv'))
    parser.add_argument('--preview', type=Path, default=ROOT / '.cache/ui-font/preview.png')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        return check()
    otf = fetch(args.fetch) if args.fetch else args.font
    if not otf:
        parser.error('--font or --fetch is required')
    generate(otf, converter(args.converter), args.preview)


if __name__ == '__main__':
    main()
