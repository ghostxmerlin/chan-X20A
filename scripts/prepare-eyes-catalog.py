#!/usr/bin/env python3
"""Verify the checked-in Soul assets and emit the firmware's bounded ID catalog."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT/'assets/soul-eyes/v2-front'
OUTPUT = ROOT/'upstream/StackChan/firmware/main/collector/eyes/catalog.generated.h'


def generate():
    manifest = json.loads((ASSETS/'manifest.json').read_text())
    states = json.loads((ASSETS/'states.json').read_text())
    mapping = json.loads((ROOT/'assets/eyes-voice-map.json').read_text())
    state_ids = list(states)
    assert len(state_ids) == 30 and state_ids[0] == 'idle'
    assert [s['id'] for s in manifest['styles']] == ['v05', 'v14', 'v18']
    assert [c['clip_id'] for c in mapping['clips']] == list(range(1,41))
    assert all(c['state'] in states and c['reason'] for c in mapping['clips'])
    enum = lambda s: s[0].upper()+s[1:]
    q = lambda s: json.dumps(s, ensure_ascii=False)
    rows = []
    for style in manifest['styles']:
        assert [a['id'] for a in style['animations']] == state_ids
        for a in style['animations']:
            assert a['path'] == f'sdcard/soul/{style["id"]}/{a["id"]}.soul'
            data = (ASSETS/a['path']).read_bytes()
            assert len(data) == a['bytes'] <= 262144
            assert hashlib.sha256(data).hexdigest() == a['sha256']
            assert a['frames'] == len(a['durations_ms']) == 8
            assert sum(a['durations_ms']) == a['duration_ms']
            sha = ','.join('0x'+a['sha256'][i:i+2] for i in range(0,64,2))
            times = ','.join(map(str,a['durations_ms']))
            rows.append(f'    {{Style::{style["id"].upper()},State::{enum(a["id"])},{a["bytes"]},{a["duration_ms"]},{{{times}}},{{{sha}}}}},')
    voices = ['State::Idle']+[f'State::{enum(c["state"])}' for c in mapping['clips']]
    return '''// Generated by scripts/prepare-eyes-catalog.py; do not edit.
#pragma once
#include <cstdint>
#include <cstddef>
#include <cstring>
namespace collector::eyes {
enum class Style : uint8_t { V05, V14, V18, Invalid=255 };
enum class State : uint8_t { '''+', '.join(map(enum,state_ids))+''', Invalid=255 };
inline constexpr size_t kStyleCount=3, kStateCount=30, kFrameCount=8;
inline constexpr size_t kPixels=320*240, kAssetCapacity=256*1024;
struct Asset { Style style; State state; uint32_t bytes, duration_ms; uint16_t durations[8]; uint8_t sha256[32]; };
inline constexpr const char* kStyleIds[]={"v05","v14","v18"};
inline constexpr const char* kStyleLabels[]={"金色猫眼","绿色机甲眼","奶油白眼睛"};
inline constexpr const char* kStateIds[]={'''+','.join(map(q,state_ids))+'''};
inline constexpr const char* kStateLabels[]={'''+','.join(q(states[s]['label']) for s in state_ids)+'''};
inline constexpr Asset kAssets[]={
'''+ '\n'.join(rows)+'''
};
inline constexpr State kVoiceStates[]={'''+','.join(voices)+'''};
inline bool valid(Style s) { return size_t(s)<kStyleCount; }
inline bool valid(State s) { return size_t(s)<kStateCount; }
inline const char* style_id(Style s) { return valid(s)?kStyleIds[size_t(s)]:nullptr; }
inline const char* state_id(State s) { return valid(s)?kStateIds[size_t(s)]:nullptr; }
inline Style parse_style(const char* s) { for (size_t i=0;s && i<kStyleCount;++i) if (!std::strcmp(s,kStyleIds[i])) return Style(i); return Style::Invalid; }
inline State parse_state(const char* s) { for (size_t i=0;s && i<kStateCount;++i) if (!std::strcmp(s,kStateIds[i])) return State(i); return State::Invalid; }
inline const Asset* asset(Style s,State state) { return valid(s)&&valid(state)?&kAssets[size_t(s)*kStateCount+size_t(state)]:nullptr; }
inline State voice_state(int clip) { return clip>0 && clip<41?kVoiceStates[clip]:State::Idle; }
} // namespace collector::eyes
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        assert OUTPUT.read_text() == content, 'Regenerate the firmware eyes catalog'
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True)
        OUTPUT.write_text(content)
    print('Eyes catalog: 90 assets and 40 voice mappings verified')
